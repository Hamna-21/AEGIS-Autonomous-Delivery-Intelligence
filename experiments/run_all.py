def ci95(values):
    values = [float(x) for x in values]
    if not values:
        return 0.0, 0.0
    mean = sum(values) / len(values)
    if len(values) == 1:
        return mean, mean
    variance = sum((x - mean) ** 2 for x in values) / (len(values) - 1)
    margin = 1.96 * (variance / len(values)) ** 0.5
    return mean - margin, mean + margin


def write_csv(path, rows):
    path.parent.mkdir(parents=True, exist_ok=True)
    rows = list(rows)
    if not rows:
        return
    fields = list(rows[0])
    with path.open("w", newline="", encoding="utf-8") as stream:
        writer = csv.DictWriter(stream, fieldnames=fields)
        writer.writeheader(); writer.writerows(rows)


def generated_grid(rng, size=5, obstacle_probability=0.0):
    grid = np.zeros((size, size), dtype=int)
    for row in range(size):
        for col in range(size):
            grid[row, col] = rng.choices([0, 1, 2, 3], [0.60, 0.20, 0.14, 0.06])[0]
    for row in range(size):
        for col in range(size):
            if rng.random() < obstacle_probability and (row, col) not in {(0, 0), (size - 1, size - 1)}:
                grid[row, col] = -1
    return grid


def directed_edges(grid):
    from world.transitions import legal_neighbors
    edges = set()
    for row in range(grid.shape[0]):
        for col in range(grid.shape[1]):
            cell = (row, col)
            if grid[cell] < 0:
                continue
            for nxt in legal_neighbors(grid, cell):
                if (row + col) % 3 != 0 or nxt[0] >= row:
                    edges.add((cell, nxt))
    return edges


def search_scenario(seed, config):
    rng = random.Random(seed)
    grid = generated_grid(rng)
    start = (0, 0); stop = (grid.shape[0] - 1, grid.shape[1] - 1)
    flooded = set()
    flood_enabled = config in {"flood", "flood_one_way"}
    one_way = config in {"one_way", "flood_one_way"}
    if flood_enabled:
        flooded.add((rng.randrange(grid.shape[0]), rng.randrange(grid.shape[1])))
        flooded.discard(start); flooded.discard(stop)
    return grid, start, [stop], flooded, flood_enabled, one_way


def run_search_experiments():
    rows = []
    configurations = ["baseline", "flood", "one_way", "flood_one_way"]
    for config_index, config in enumerate(configurations):
        for scenario in range(SCENARIOS_PER_CONFIGURATION):
            seed = SEED + config_index * 10000 + scenario
            grid, start, stops, flooded, flood_enabled, one_way = search_scenario(seed, config)
            problem = DeliveryProblem(grid, start, stops, TERRAIN_COST,
                                     allowed_edges=directed_edges(grid) if one_way else None,
                                     flooded_cells=flooded, flood_enabled=flood_enabled, flood_interval=5)
            for algorithm, solver in SEARCH_ALGORITHMS:
                began = time.perf_counter(); result = solver(problem)
                row = {"part": "B", "configuration": config, "scenario": scenario,
                       "seed": seed, "algorithm": algorithm, "found": result.found,
                       "cost": result.cost if result.found else "", "nodes_expanded": result.nodes_expanded,
                       "runtime_seconds": result.runtime_seconds, "memory_states": result.max_memory_states,
                       "path_length": len(result.path), "wall_seconds": time.perf_counter() - began}
                row.update(team_fields()); rows.append(row)
    write_csv(OUT / "part_b_search_raw.csv", rows)
    return rows


def game_for_seed(seed, horizon=12):
    rng = random.Random(seed); size = 5
    passable = {(r, c) for r in range(size) for c in range(size)}
    for cell in ((1, 2), (2, 2), (3, 3)): passable.discard(cell)
    start = (size - 1, 0)
    rival = (0, size - 1) if rng.random() > 0.33 else (size - 2, 1)
    target = (0, 0) if seed % 2 else (0, 1)
    return ReducedDeliveryGame(passable, start, rival, [target], horizon=horizon)


def execute_game(game, depth, slip_probability, seed, planner):
    rng = random.Random(seed); state = game.start_state; replans = 0
    while game.terminal_value(state) is None:
        decision = planner(game, state, depth=depth); actual = decision.move
        if rng.random() < slip_probability:
            actual = rng.choice([action for action, _ in game.legal_moves(state.agent)]); replans += 1
        state = game.move(state, "agent", actual)
        if game.terminal_value(state) is not None: break
        state = min((game.move(state, "rival", action) for action, _ in game.legal_moves(state.rival)), key=game.evaluation)
    value = game.terminal_value(state)
    return ("win" if value == 1 else "loss" if value == -1 else "draw"), replans


def run_rival_experiments():
    rows = []
    for config, slip in [("deterministic", 0.0), ("stochastic_slip", 0.11)]:
        for scenario in range(SCENARIOS_PER_CONFIGURATION):
            seed = SEED + 50000 + scenario; game = game_for_seed(seed)
            for depth in (2, 3, 4):
                for algorithm, planner in (("Minimax", minimax), ("Alpha-Beta", alpha_beta)):
                    decision = planner(game, depth=depth)
                    outcome, replans = execute_game(game, depth, slip, seed + depth, planner)
                    row = {"part": "C", "configuration": config, "scenario": scenario,
                           "seed": seed, "depth": depth, "algorithm": algorithm,
                           "value": decision.value, "selected_move": decision.move,
                           "nodes": decision.stats.nodes, "cutoffs": decision.stats.cutoffs,
                           "pruning_percent": "", "outcome": outcome, "replans": replans}
                    row.update(team_fields()); rows.append(row)
    by_key = {}
    for row in rows: by_key.setdefault((row["configuration"], row["scenario"], row["depth"]), {})[row["algorithm"]] = row
    for pair in by_key.values():
        mm, ab = pair["Minimax"], pair["Alpha-Beta"]
        ab["pruning_percent"] = 100 * (int(mm["nodes"]) - int(ab["nodes"])) / max(1, int(mm["nodes"]))
    write_csv(OUT / "part_c_rival_raw.csv", rows)
    return rows


